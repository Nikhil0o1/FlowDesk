#!/usr/bin/env node
/**
 * Regenerate render.yaml header rules and deploy/cloudflare-response-headers.json
 * from vercel.json (which must match src/lib/securityHeaders.ts).
 *
 * Usage: node scripts/sync-deploy-headers.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

function headersFromVercel() {
  const vercel = JSON.parse(readFileSync(join(root, 'vercel.json'), 'utf8'))
  const rules = vercel.headers?.[0]?.headers
  if (!Array.isArray(rules) || rules.length === 0) {
    throw new Error('vercel.json: expected headers[0].headers array')
  }
  return Object.fromEntries(rules.map(({ key, value }) => [key, value]))
}

function yamlQuote(value) {
  if (/[:#'"{}[\],&*?|>!%@`]/.test(value) || value.trim() !== value) {
    return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`
  }
  return value
}

function renderYamlHeaders(headers) {
  return Object.entries(headers)
    .map(
      ([name, value]) =>
        `      - path: /*\n        name: ${name}\n        value: ${yamlQuote(value)}`,
    )
    .join('\n')
}

function renderYamlTemplate(headerBlock) {
  return `# Render Blueprint — static SPA (production). Vercel uses vercel.json for the same headers.
# Link this repo in Render Dashboard → Blueprints, or paste headers under Settings → Headers.
# Keep headers in sync with src/lib/securityHeaders.ts (see tests/security/securityHeaders.test.ts).
# Generated by scripts/sync-deploy-headers.mjs — edit vercel.json + securityHeaders.ts, then re-run.
services:
  - type: web
    name: flowdesk-ui
    runtime: static
    buildCommand: npm ci && npm run build
    staticPublishPath: dist
    domains:
      - flowdesk.brightcone.ai
    routes:
      - type: rewrite
        source: /*
        destination: /index.html
    headers:
${headerBlock}
`
}

function cloudflareJson(headers) {
  return `${JSON.stringify(
    {
      _comment:
        'Cloudflare Transform Rules → Modify response header (one rule per entry). Expression: (http.host eq "flowdesk.brightcone.ai"). Regenerate with: node scripts/sync-deploy-headers.mjs',
      headers,
    },
    null,
    2,
  )}\n`
}

const headers = headersFromVercel()
writeFileSync(join(root, 'render.yaml'), renderYamlTemplate(renderYamlHeaders(headers)), 'utf8')
writeFileSync(join(root, 'deploy/cloudflare-response-headers.json'), cloudflareJson(headers), 'utf8')
console.log('Synced render.yaml and deploy/cloudflare-response-headers.json from vercel.json')
